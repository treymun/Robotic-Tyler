// Compiles tools/trivia/questions.txt into browser-extension/trivia-bank.js and
// refuses anything that would make a bad question in chat. Used by tools/build.mjs.
export const PER_CATEGORY=50;

export function parseQuestions(text){
 const categories=[],problems=[],seen=new Map(),aliasOwner=new Map();
 let current=null;
 for(const [index,raw] of String(text).split(/\r?\n/).entries()){
  const line=raw.trim(),at='line '+(index+1);
  if(!line||line.startsWith('#'))continue;
  const fields=line.replace(/^@/,'').split('|').map(s=>s.trim());
  if(line.startsWith('@')){
   const [id,icon,name,aliases='']=fields;
   if(!/^[a-z]+$/.test(id||'')||!icon||!name){problems.push(at+': a category needs "@ id | icon | Name | aliases"');continue;}
   current={id,icon,name,aliases:[...new Set(aliases.split(',').map(s=>s.trim().toLowerCase()).filter(a=>a&&a!==id))],rows:[]};
   for(const word of [id,...current.aliases]){if(aliasOwner.has(word))problems.push(at+': "'+word+'" already names '+aliasOwner.get(word));aliasOwner.set(word,id);}
   categories.push(current);continue;
  }
  if(!current){problems.push(at+': question before any category');continue;}
  const [level,question,answer,...wrong]=fields;
  if(fields.length!==6){problems.push(at+': expected level | question | answer | 3 wrong answers');continue;}
  if(!/^[123]$/.test(level))problems.push(at+': level must be 1, 2 or 3');
  if(!question.endsWith('?'))problems.push(at+': question should end with "?"');
  const options=[answer,...wrong];
  if(options.some(o=>!o))problems.push(at+': empty answer');
  if(new Set(options.map(o=>o.toLowerCase())).size!==4)problems.push(at+': answers must all be different');
  if(options.some(o=>o.length>60))problems.push(at+': answers must be 60 characters or fewer');
  // Steam shows square brackets literally, and Tyler's own lines must never look like a tag.
  if([question,...options].some(s=>/[\[\]<>|]/.test(s)))problems.push(at+': no [ ] < > | characters');
  const key=question.toLowerCase();if(seen.has(key))problems.push(at+': same question as '+seen.get(key));seen.set(key,at);
  current.rows.push([Number(level),question,answer,...wrong]);
 }
 for(const c of categories){
  if(c.rows.length!==PER_CATEGORY)problems.push(c.id+': has '+c.rows.length+' questions, needs '+PER_CATEGORY);
  for(const level of [1,2,3])if(c.rows.filter(r=>r[0]===level).length<5)problems.push(c.id+': needs at least 5 questions at level '+level);
 }
 return {categories,problems};
}

export function compileTrivia(text){
 const {categories,problems}=parseQuestions(text);
 if(problems.length)throw Error('tools/trivia/questions.txt:\n  '+problems.join('\n  '));
 const total=categories.reduce((n,c)=>n+c.rows.length,0);
 const body=categories.map(c=>' ['+[c.id,c.icon,c.name,c.aliases].map(v=>JSON.stringify(v)).join(',')+',[\n'+c.rows.map(r=>'  '+JSON.stringify(r)).join(',\n')+'\n ]]').join(',\n');
 return `// GENERATED by tools/build.mjs from tools/trivia/questions.txt. Edit that file, then run: node tools/build.mjs
// ROBOTIC TYLER trivia bank: ${total} questions in ${categories.length} categories.
// Row: [level (1 easy, 2 medium, 3 hard), question, correct answer, three wrong answers].
(()=>{
 const categories=[
${body}
 ];
 globalThis.TylerTriviaBank=Object.freeze(categories.map(([id,icon,name,aliases,rows])=>Object.freeze({id,icon,name,aliases:Object.freeze(aliases),
  questions:Object.freeze(rows.map((r,i)=>Object.freeze({id:id+'-'+i,level:r[0],question:r[1],answer:r[2],wrong:Object.freeze(r.slice(3))})))})));
})();
`;
}
