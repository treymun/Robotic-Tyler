// v2.31: the themed soundboard defaults (assets/theme-sounds, the owner's "25-theme soundboard pack").
// Each theme has its own audio for the ten built-in pads (Beep … Countdown). tools/build.mjs calls
// this to check the pack and to produce:
//   browser-extension/theme-sounds.mjs      the map the background reads (theme → slot → file)
//   browser-extension/sounds/themes/<theme>/<NN-name>.mp3   the 250 finished clips, as supplied
//   browser-extension/sounds/CREDITS.md, SOUND-MAP.csv       their credits and what each one is
// Only slots 1–10 are themed. Sound 11 onward is the user's own collection and is never in here.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

export const SLOT_NAMES=['Beep','Airhorn','Drumroll','Victory','Sad trombone','Alert','Coin','Jump','Laser','Countdown'];
// Measured through the real player (soundboard-audio.js) at the default volume: the pack's clips are
// about 3 dB quieter than the synthesized built-ins they replace (median short-term level), so they
// play 3 dB up, the same for all 250 (their balance and dynamics stay as supplied).
export const THEME_SOUND_LEVEL=3;
const KINDS={'source-recording':'Source recording','source-derived-arrangement':'Edited arrangement of a source recording',
 'hybrid-source-and-original-design':'Hybrid: a source recording with new sound design','original-theme-matched-design':'Original design for the theme'};

export function compileThemeSounds({root,themes}){
 const dir=path.join(root,'assets','theme-sounds'),manifest=JSON.parse(fs.readFileSync(path.join(dir,'manifest.json'),'utf8'));
 const fail=m=>{throw Error('assets/theme-sounds: '+m);};
 if(JSON.stringify(manifest.slotNames)!==JSON.stringify(SLOT_NAMES))fail('the pads must keep their names: '+SLOT_NAMES.join(', '));
 if(manifest.policy?.sharedSlotsStart!==11)fail('only slots 1–10 may be themed');
 const ids=manifest.themes.map(t=>t.id);
 for(const t of themes)if(!ids.includes(t))fail('no sounds for the '+t+' theme');
 for(const t of ids)if(!themes.includes(t))fail(t+' is not one of the app\'s themes');
 const map={},files=[];
 for(const t of manifest.themes){
  if(t.clips.length!==10)fail(t.id+' needs exactly ten clips');
  map[t.id]={name:t.name,clips:t.clips.map((c,i)=>{
   if(c.slot!==i+1||c.slotName!==SLOT_NAMES[i])fail(t.id+' clip '+(i+1)+' must be slot '+(i+1)+' ('+SLOT_NAMES[i]+')');
   if(!/^audio\/[a-z0-9]+\/\d\d-[a-z-]+\.mp3$/.test(c.file)||!c.file.startsWith('audio/'+t.id+'/'))fail(t.id+': unexpected file '+c.file);
   const bytes=fs.readFileSync(path.join(dir,c.file));
   if(crypto.createHash('sha256').update(bytes).digest('hex')!==c.sha256)fail(c.file+' does not match the manifest');
   // The app's clip contract: base64 of at most 700,000 characters, more than 0 and at most 12 seconds.
   if(Math.ceil(bytes.length/3)*4>700000||!(c.seconds>0&&c.seconds<=12))fail(c.file+' is outside the clip limits');
   if(!KINDS[c.provenanceKind])fail(c.file+': unknown provenance '+c.provenanceKind);
   const rel='sounds/themes/'+c.file.slice('audio/'.length);files.push([rel,bytes]);
   return {file:rel,seconds:Math.round(c.seconds*1000)/1000,cue:String(c.caption).slice(0,60),kind:c.provenanceKind};})};
 }
 files.push(['sounds/CREDITS.md',fs.readFileSync(path.join(dir,'CREDITS.md'))]);
 files.push(['sounds/SOUND-MAP.csv',fs.readFileSync(path.join(dir,'SOUND-MAP.csv'))]);
 const module=`// GENERATED by tools/build.mjs (tools/sounds/compile.mjs) from assets/theme-sounds/manifest.json.
// The ten built-in pads' sounds for each theme (v2.31). Sound 11 onward is the user's own collection:
// themeSound() returns null for it. Credits: sounds/CREDITS.md; what each clip is: sounds/SOUND-MAP.csv.
const T=${JSON.stringify(map)};
export const THEME_SOUND_LEVEL=${THEME_SOUND_LEVEL};
export const THEME_SOUND_KINDS=${JSON.stringify(KINDS)};
/** The packaged clip for one of the first ten pads in a theme (an unknown theme gets Steam's), or null. */
export function themeSound(theme,slot){
 if(!Number.isInteger(slot)||slot<1||slot>10)return null;
 const t=Object.hasOwn(T,theme)?theme:'steam',c=T[t].clips[slot-1];
 return {theme:t,themeName:T[t].name,slot,...c,level:THEME_SOUND_LEVEL};
}
export const THEME_SOUND_THEMES=Object.freeze(Object.keys(T));
`;
 return {module,files};
}
