import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {Memory} from '../app/companion/memory.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'browser-extension/manifest.json'),'utf8'));
for(const entry of manifest.content_scripts)for(const f of entry.js)assert.ok(fs.existsSync(path.join(root,'browser-extension',f)),f+' should be packaged');
const ctx={globalThis:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'browser-extension/auto-policy.js'),'utf8'),ctx);
const Policy=ctx.globalThis.TylerAutoPolicy;
const p=new Policy();p.enabled=true;p.people=0;
assert.equal(p.cooldown,2200);p.lastDirect=true;assert.equal(p.cooldown,900);p.speed='cautious';assert.equal(p.cooldown,5000);p.people=1;assert.equal(p.cooldown,1500);
let obj={};const storage={async get(k){return {[k]:obj[k]};},async set(v){Object.assign(obj,v)}};
const memory=new Memory(storage);
await memory.write('room:data-chatid:abc',[{role:'user',content:'test'}]);
assert.equal((await memory.read('room:data-chatid:abc'))[0].content,'test');
await memory.writeFriend('76561198000000000',[{role:'user',content:'hey'}]);
assert.equal((await memory.readFriend('76561198000000000')).length,1);
assert.equal((await memory.readFriend('invalid')).length,0);
const preload=fs.readFileSync(path.join(root,'app/steam-preload.cjs'),'utf8');
// v2.4: the preload is generated from the extension's content scripts (tools/build.mjs).
assert.match(preload,/GENERATED by tools\/build\.mjs/);
// v2.19: the speech detector bridge, Live voice and the leave fix run in the desktop Steam window too.
for(const f of ['content.js','automatic.js','chat-bus.js','moderation.js','admin.js','neural-bridge.js','live-voice.js','steam-voice-fix.js'])assert.match(preload,new RegExp('/\\* '+f.replace('.','\\.')+' \\*/'),f+' should be bundled for desktop');
for(const f of ['screen-awareness.js','music.js','game-hub.js'])assert.doesNotMatch(preload,new RegExp('/\\* '+f.replace('.','\\.')+' \\*/'),f+' should stay out of the desktop bundle');
assert.match(preload,/const processed=new WeakMap/);
assert.match(preload,/data-chatid/);
const main=fs.readFileSync(path.join(root,'app/main.cjs'),'utf8');
assert.match(main,/RoboticTylerHydraCloudV12/);
assert.doesNotMatch(main,/path\.join\(root,?'RoboticTyler'\)/);
console.log('Packaging, policy, isolation, and memory checks passed');
