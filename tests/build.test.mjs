import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {execFileSync} from 'node:child_process';

const root=path.resolve(import.meta.dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');

test('generated desktop files and ui-template.js are up to date with their sources',()=>{
 const out=execFileSync(process.execPath,[path.join(root,'tools','build.mjs'),'--check'],{encoding:'utf8'});
 assert.match(out,/up to date/);
});

test('every element id the panel shell script uses exists in ui/panel.html',()=>{
 const html=read('browser-extension/ui/panel.html');const ids=new Set([...html.matchAll(/\sid="([^"]+)"/g)].map(m=>m[1]));
 const used=new Set([...read('browser-extension/content.js').matchAll(/\$\('([A-Za-z0-9_-]+)'\)/g)].map(m=>m[1]));
 for(const id of ['hudVoice','hudSpend','hudLatency'])used.add(id);
 const missing=[...used].filter(id=>!ids.has(id));
 assert.deepEqual(missing,[]);
});

test('compiled template carries the shared design tokens and stays a plain string bundle',()=>{
 const box={};box.globalThis=box;vm.runInNewContext(read('browser-extension/ui-template.js'),box);
 const ui=box.TylerUI;
 assert.match(ui.css,/--rt-accent:/);assert.match(ui.css,/\.tally\{/);
 assert.match(ui.html,/id="featureMount"/);
 assert.ok(ui.markup.startsWith('<style>'),'fallback markup still inlines the stylesheet');
 assert.equal(read('voice-app/tokens.css'),read('browser-extension/ui/tokens.css'));
});

test('desktop companion is generated, with only the documented desktop overrides',()=>{
 const generated=read('app/companion/GENERATED.txt');assert.match(generated,/generated by tools\/build\.mjs/);
 for(const f of ['background.js','memory.mjs','settings-navigation.js','v23-settings.js'])
  assert.equal(read('app/companion/'+f),read('browser-extension/'+f),f+' is copied verbatim');
 assert.match(read('app/companion/settings.html'),/<body data-desktop="true">/);
 for(const f of ['settings.js','v22-settings.js'])assert.equal(read('app/companion/'+f),read('app/desktop-overrides/'+f));
});
