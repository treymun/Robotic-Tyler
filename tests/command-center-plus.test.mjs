import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {routeComplexity} from '../app/companion/quality.mjs';
assert.equal(routeComplexity('lol nice'), 'fast');
assert.equal(routeComplexity('explain a good strategy for defending with towers'), 'deep');
assert.equal(routeComplexity('a'.repeat(300)), 'deep');
const context={globalThis:{}};
vm.runInNewContext(readFileSync(new URL('../app/companion/soundboard-core.js',import.meta.url),'utf8'),context);
const arcade=context.globalThis.TylerSoundboard.arcade;
const r=arcade('!game trivia',{},()=>0,1000);
assert.match(r.text,/TRIVIA/i);
assert.equal(r.next.round.answer,'super mushroom');
const win=arcade('!game guess super mushroom',r.next,()=>0,1100);
assert.equal(win.next.wins,1);
assert.equal(win.next.round,null);
const fail=arcade('!game guess not it',r.next,()=>0,1100);
assert.equal(fail.next.round.left,5);
const long=(arcade('!game help',{},()=>0,1000)).text;
assert.match(long,/trivia/);
console.log('Command Center Plus and arcade smoke tests passed');
